import re
import sys

YEAR = "2026"

COPYRIGHT_RE = re.compile(r"Copyright \d{4} Battelle Energy Alliance, LLC")
COPYRIGHT_REPLACEMENT = f"Copyright {YEAR} Battelle Energy Alliance, LLC"

AUTO_GENERATED_MARKER = "// <auto-generated>"

SKIP_DIRS = {"obj", "bin", "node_modules", "dist", ".angular", ".git", "__pycache__"}

SKIP_PATHS = {
    os.path.join(
        "CSETWebApi", "CSETWeb_Api", "CSETWebCore.UpgradeLibrary", "VersionUpgrader"
    ),
}

