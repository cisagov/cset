"""
Update copyright headers in .cs, .ts, and .html files.

- Updates existing "Copyright YYYY Battelle Energy Alliance, LLC" to 2026.
- Adds the appropriate copyright header if missing entirely.
- Skips auto-generated files (// <auto-generated>).
- Skips files in obj/, bin/, node_modules/, dist/, .angular/ directories.
"""

