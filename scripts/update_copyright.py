def should_skip_dir(dirpath: str, root: str) -> bool:
    parts = dirpath.split(os.sep)
    if any(part in SKIP_DIRS for part in parts):
        return True
    rel = os.path.relpath(dirpath, root)
    for skip_path in SKIP_PATHS:
        if rel == skip_path or rel.startswith(skip_path + os.sep):
            return True
    return False


def has_copyright(content: str) -> bool:
    return bool(COPYRIGHT_RE.search(content))


def is_auto_generated(content: str) -> bool:
    return AUTO_GENERATED_MARKER in content[:200]


def update_year(content: str) -> str:
    return COPYRIGHT_RE.sub(COPYRIGHT_REPLACEMENT, content)


def add_header(content: str, header: str) -> str:
    # Preserve BOM if present
    bom = ""
    if content.startswith("\ufeff"):
        bom = "\ufeff"
        content = content[1:]

    return bom + header + content


def get_header_for_ext(ext: str) -> str:
    if ext == ".cs":
        return CS_HEADER
    elif ext == ".ts":
        return TS_HEADER
    elif ext == ".html":
        return HTML_HEADER
    return ""


INCLUDE_DIRS = {"CSETWebNg", "CSETWebApi"}


def collect_files(root: str, extensions: set[str]) -> list[str]:
    files = []
    search_roots = [
        os.path.join(root, d)
        for d in INCLUDE_DIRS
        if os.path.isdir(os.path.join(root, d))
    ]

    for search_root in search_roots:
        for dirpath, dirnames, filenames in os.walk(search_root):
            # Prune skipped directories in-place
            dirnames[:] = [
                d
                for d in dirnames
                if d not in SKIP_DIRS
                and not any(
                    os.path.relpath(os.path.join(dirpath, d), root) == sp
                    for sp in SKIP_PATHS
                )
            ]

            if should_skip_dir(dirpath, root):
                continue

            for filename in filenames:
                ext = os.path.splitext(filename)[1].lower()
                if ext in extensions:
                    files.append(os.path.join(dirpath, filename))
    return files


def process_file(filepath: str, dry_run: bool = False) -> str | None:
    """Process a single file. Returns a status string or None if skipped."""
    ext = os.path.splitext(filepath)[1].lower()

    try:
        with open(filepath, "r", encoding="utf-8-sig") as f:
            content = f.read()
    except (UnicodeDecodeError, PermissionError):
        return None

    # Re-read with BOM preserved for writing back
    with open(filepath, "rb") as f:
        raw = f.read()

    has_bom = raw[:3] == b"\xef\xbb\xbf"

    if is_auto_generated(content):
        return None

    if has_copyright(content):
        if f"Copyright {YEAR}" in content:
            return None  # Already up to date

        updated = update_year(content)
        if not dry_run:
            write_content = updated
            if has_bom:
                write_content = "\ufeff" + updated.lstrip("\ufeff")
            with open(filepath, "w", encoding="utf-8", newline="") as f:
                f.write(write_content)
        return "updated"
    else:
        header = get_header_for_ext(ext)
        if not header:
            return None

        updated = add_header(content, header)
        if not dry_run:
            write_content = updated
            if has_bom:
                write_content = "\ufeff" + updated.lstrip("\ufeff")
            with open(filepath, "w", encoding="utf-8", newline="") as f:
                f.write(write_content)
        return "added"


def main():
    dry_run = "--dry-run" in sys.argv
    root = os.path.dirname(os.path.abspath(__file__))

    if dry_run:
        print("=== DRY RUN MODE (no files will be modified) ===\n")

    extensions = {".cs", ".ts", ".html"}
    files = collect_files(root, extensions)
    files.sort()

    updated_count = 0
    added_count = 0
    skipped_count = 0

    for filepath in files:
        rel = os.path.relpath(filepath, root)
        result = process_file(filepath, dry_run=dry_run)

        if result == "updated":
            print(f"  UPDATED  {rel}")
            updated_count += 1
        elif result == "added":
            print(f"  ADDED    {rel}")
            added_count += 1
        else:
            skipped_count += 1

    print(
        f"\nDone. Updated: {updated_count}, Added: {added_count}, Skipped: {skipped_count}"
    )


if __name__ == "__main__":
    main()
